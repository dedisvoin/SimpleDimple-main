/// Соответствие типа объекта паре «номер меша — номер материала».
///
/// Ноль означает пустую ячейку. Объекты типов 2 и 3 используют один и тот же
/// меш с разными материалами.
pub fn object_type(kind: u8) -> Option<(usize, usize)> {
    match kind {
        0 => None,
        1 => Some((1, 1)),
        2 => Some((2, 2)),
        3 => Some((2, 3)),
        _ => None,
    }
}

